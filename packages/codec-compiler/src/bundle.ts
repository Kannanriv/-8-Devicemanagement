import JSZip from "jszip";
import type { DeviceCodecSpec, Field } from "@hash8/dcs-schema";
import { generatePlugin, listTargets, type PluginTarget } from "./index";
import { GENERATOR } from "./common";

/** Zip with one folder per target, plus README.md, LICENSE and spec.json at the root. */
export async function buildBundle(spec: DeviceCodecSpec, targets: PluginTarget[]): Promise<Uint8Array> {
  const zip = new JSZip();
  const unavailable: { target: PluginTarget; reason: string }[] = [];

  for (const target of targets) {
    try {
      for (const f of generatePlugin(spec, target)) zip.file(`${target}/${f.path}`, f.content);
    } catch (err) {
      unavailable.push({ target, reason: err instanceof Error ? err.message : String(err) });
    }
  }

  zip.file("README.md", readme(spec, targets, unavailable));
  zip.file("LICENSE", APACHE_2);
  zip.file("spec.json", JSON.stringify(spec, null, 2) + "\n");
  return zip.generateAsync({ type: "uint8array", compression: "DEFLATE" });
}

interface FieldRow {
  message: string;
  direction: string;
  path: string;
  type: string;
  unit: string;
  description: string;
}

function rows(spec: DeviceCodecSpec): FieldRow[] {
  const out: FieldRow[] = [];
  const walk = (message: string, direction: string, fields: Field[], prefix: string) => {
    for (const f of fields) {
      if (f.kind === "const" || f.kind === "checksum") continue;
      if (f.kind === "group") walk(message, direction, f.fields, `${prefix}${f.name}.`);
      else if (f.kind === "repeat") walk(message, direction, f.fields, `${prefix}${f.name}[].`);
      else if (f.kind === "switch") {
        for (const fs of Object.values(f.cases)) walk(message, direction, fs, prefix);
        if (f.default) walk(message, direction, f.default, prefix);
      } else if (!f.hidden) {
        const type = f.type + (f.bits ? `:${f.bits}` : "");
        out.push({
          message,
          direction,
          path: prefix + f.name,
          type: f.enum ? `${type} (enum)` : type,
          unit: f.unit ?? "",
          description: (f.description ?? "").replace(/\|/g, "\\|").replace(/\n/g, " "),
        });
      }
    }
  };
  for (const m of spec.uplink) walk(m.name, "uplink", m.fields, "");
  for (const m of spec.downlink ?? []) walk(m.name, "downlink", m.fields, "");
  // switch branches often repeat the same field
  const seen = new Set<string>();
  return out.filter((r) => {
    const k = `${r.message}|${r.path}|${r.type}`;
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
}

function readme(spec: DeviceCodecSpec, targets: PluginTarget[], unavailable: { target: PluginTarget; reason: string }[]): string {
  const info = new Map(listTargets().map((t) => [t.target, t]));
  const d = spec.device;
  const lines: string[] = [];
  lines.push(`# ${d.vendor} ${d.model} — decoder plugins`, "");
  lines.push(
    `Codec \`${spec.id}\` v${spec.version}${d.firmware ? ` · firmware ${d.firmware}` : ""}. Generated by ${GENERATOR} from the Device Codec Spec in \`spec.json\` — no Excel decoding required.`,
    "",
  );
  if (d.description) lines.push(d.description, "");
  lines.push("## Included targets", "");
  for (const t of targets) {
    const i = info.get(t);
    const missing = unavailable.find((u) => u.target === t);
    lines.push(`- **${i?.label ?? t}** (\`${t}/\`)${missing ? ` — _not included: ${missing.reason}_` : ` — ${i?.description ?? ""}`}`);
  }
  lines.push("", "## Integrate", "");
  lines.push("- **The Things Stack (TTN)** — paste the `ts013/` formatter into *Payload formatters → Custom JavaScript*.");
  lines.push("- **ChirpStack** — device profile → *Codec: JavaScript functions*, paste the `ts013/` file.");
  lines.push("- **Node.js / TypeScript** — copy `ts/` into your project: `import { decode, encode } from './codec'`.");
  lines.push("- **Python** — copy the module from `python/`: `decode(bytes.fromhex('...'), port=1)`.");
  lines.push("- **Go** — vendor the `go/` package: `codec.Decode(payload, &port, topic)`.");
  lines.push("- **Java** — add the `java/` sources: `Codec.decode(bytes, port, topic)`.");
  lines.push("- **C (firmware / gateways)** — compile the `c/` sources with C99; no heap allocation.");
  lines.push(
    "",
    "Every target returns `{ ok, message, data, warnings }` on success and `{ ok: false, errors }` otherwise, identical across languages. Each folder ships tests generated from the spec's test vectors.",
    "",
  );
  lines.push("## Fields", "");
  lines.push("| message | direction | field | type | unit | description |", "|---|---|---|---|---|---|");
  for (const r of rows(spec)) lines.push(`| ${r.message} | ${r.direction} | ${r.path} | ${r.type} | ${r.unit} | ${r.description} |`);
  lines.push("", "## Test vectors", "", `${spec.vectors?.length ?? 0} vectors are embedded in \`spec.json\`.`, "");
  return lines.join("\n");
}

