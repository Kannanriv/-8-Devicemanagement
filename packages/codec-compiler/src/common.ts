import type { DeviceCodecSpec, Field, TestVector } from "@hash8/dcs-schema";

export interface GeneratedFile {
  path: string;
  content: string;
}

export const GENERATOR = "#8 Device Management codec compiler";

/** Identifier-safe slug of the codec id: "acme.th-1" -> "acme_th_1". */
export function slug(spec: DeviceCodecSpec): string {
  return spec.id.replace(/[^a-z0-9]+/gi, "_").replace(/^_+|_+$/g, "").toLowerCase();
}

export function pascal(s: string): string {
  return s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
}

/** Header lines (without comment syntax). */
export function headerLines(spec: DeviceCodecSpec, what: string): string[] {
  return [
    `${spec.device.vendor} ${spec.device.model} — ${what}`,
    `Codec: ${spec.id} v${spec.version} (DCS ${spec.dcs})`,
    `Generated by ${GENERATOR}. DO NOT EDIT — regenerate from the Device Codec Spec.`,
    `License: ${spec.meta?.license ?? "Apache-2.0"}`,
  ];
}

export function blockHeader(spec: DeviceCodecSpec, what: string): string {
  return `/*\n${headerLines(spec, what).map((l) => ` * ${l}`).join("\n")}\n */\n`;
}

export function lineHeader(spec: DeviceCodecSpec, what: string, prefix: string): string {
  return headerLines(spec, what).map((l) => `${prefix} ${l}`).join("\n") + "\n";
}

/** The spec as embedded in plugins: layout + semantics only (no sources, vectors or meta). */
export function runtimeSpec(spec: DeviceCodecSpec): Record<string, unknown> {
  const strip = (fields: Field[]): unknown[] =>
    fields.map((f) => {
      const { source: _s, description: _d, ...rest } = f as Field & { source?: unknown; description?: unknown };
      const r = rest as Record<string, unknown>;
      if ("fields" in f && Array.isArray(f.fields)) r.fields = strip(f.fields);
      if (f.kind === "switch") {
        r.cases = Object.fromEntries(Object.entries(f.cases).map(([k, v]) => [k, strip(v)]));
        if (f.default) r.default = strip(f.default);
      }
      if (f.kind === "scalar" || f.kind === "checksum" || f.kind === "const") {
        delete r.unit;
        delete r.semantic;
      }
      return r;
    });
  const msgs = (list: DeviceCodecSpec["uplink"] | undefined) =>
    (list ?? []).map((m) => ({ name: m.name, ...(m.when ? { when: m.when } : {}), fields: strip(m.fields) }));
  return {
    id: spec.id,
    version: spec.version,
    defaults: { endian: spec.defaults?.endian ?? "big" },
    uplink: msgs(spec.uplink),
    downlink: msgs(spec.downlink),
  };
}

export function cleanHex(hex: string): string {
  return hex.replace(/^0x/i, "").replace(/[\s:-]/g, "").toLowerCase();
}

export function vectors(spec: DeviceCodecSpec): TestVector[] {
  return spec.vectors ?? [];
}

/** JSON string literal usable in JS/TS/Java/Go/C/Python source (ASCII-only, escaped). */
export function strLit(s: string): string {
  return JSON.stringify(s).replace(/[\u007f-￿]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
}
